def expand_query_terms(query: str) -> tuple[str, ...]:
    expanded: list[str] = []
    for pattern, terms in EXPANSION_RULES:
        if pattern.search(query):
            expanded.extend(terms)
    return tuple(dict.fromkeys(expanded))


def preferred_program_term(terms: tuple[str, ...]) -> str:
    return next((term for term in PROGRAM_ANCHORS if term in terms), "")
